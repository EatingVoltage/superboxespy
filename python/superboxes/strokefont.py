ADVANCE = {".": 1.0, ",": 1.0, ":": 1.0, " ": 3.0}   # grid units incl. the gap; default 5 (glyph 4 + gap 1)
NARROW = {".", ",", ":"}


def _glyph(ch):
    if ch in GLYPHS:
        return GLYPHS[ch]
    return GLYPHS.get(ch.upper(), [])


def units(s):
    """Width of `s` in grid units (without the trailing gap)."""
    if not s:
        return 0.0
    return sum(ADVANCE.get(ch, 5.0) for ch in s) - (0.0 if s[-1] in ADVANCE else 1.0)


def width(s, height):
    return units(s) * height / 6.0


def text(s, x, y, height, align="left"):
    """Polylines of `s` with cap height `height`, baseline y. align: left | center | right (around x)."""
    k = height / 6.0
    w = units(s) * k
    x0 = x - (w / 2 if align == "center" else w if align == "right" else 0.0)
    lines = []
    cx = x0
    for ch in s:
        for stroke in _glyph(ch):
            lines.append(LineString([(cx + px * k, y + py * k) for px, py in stroke]))
        cx += ADVANCE.get(ch, 5.0) * k
    return MultiLineString(lines)
