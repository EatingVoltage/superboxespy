"""Single-stroke lettering for engraved labels, comb values and the maker's mark.

Glyphs are polylines on a 4 x 6 grid (cap height 6, y up). One pass of the LINE layer per stroke: fast to
engrave, no font file needed, and the same strokes serve as T1 labels on screen. Lower case is drawn as upper
case. Unknown characters advance like a space.
"""
from shapely.geometry import LineString, MultiLineString

